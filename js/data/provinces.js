export const PROVINCE_LIST = Object.freeze(Object.values(PROVINCES));
export const PROVINCES_DATA = PROVINCE_LIST;

export function getProvinceById(id) {
  return PROVINCES[id] || null;
}

export function getProvincesByFaction(factionId) {
  return PROVINCE_LIST.filter(p => p.controllingFaction === factionId);
}

export function areProvincesAdjacent(provAId, provBId) {
  const pA = PROVINCES[provAId];
  return pA ? pA.connections.includes(provBId) : false;
}

